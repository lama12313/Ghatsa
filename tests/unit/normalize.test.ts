import { describe, expect, it } from 'vitest';
import { normalize } from '../../src/lib/normalize';

describe('normalize', () => {
  const same: [string, string][] = [
    ['مُحَمَّد', 'محمد'],
    ['محـــمد', 'محمد'],
    ['أحمد', 'احمد'],
    ['إبراهيم', 'ابراهيم'],
    ['آدم', 'ادم'],
    ['ٱلقمر', 'قمر'],
    ['مؤمن', 'مومن'],
    ['مسائل', 'مسايل'],
    ['فاطمة', 'فاطمه'],
    ['مصطفى', 'مصطفي'],
    ['المغرب', 'مغرب'],
    ['  السعودية  ', 'سعوديه'],
    ['عبد الله', 'عبدالله'],
    ['عبد الرحمن', 'عبدالرحمن'],
    ['كوريا الجنوبية', 'كوريا جنوبيه'],
    ['٣', '3'],
    ['١٢٣', '123'],
    ['۴', '4'],
    ['مصر!', 'مصر'],
    ['ساو-تومي', 'ساو تومي'],
    ['«تونس»', 'تونس'],
    ['Paris', 'paris'],
    ['سماء', 'سما'],
    ['ڤيتنام', 'فيتنام'],
    ['کابل', 'كابل'],
  ];
  it.each(same)('«%s» = «%s»', (a, b) => {
    expect(normalize(a)).toBe(normalize(b));
  });

  it('لا يشيل «ال» من كلمة قصيرة', () => {
    expect(normalize('الف')).toBe('الف');
  });

  it('يرجع نص فاضي للمدخلات الفاضية', () => {
    expect(normalize('  !! ')).toBe('');
  });
});
